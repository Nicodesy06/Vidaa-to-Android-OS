const { chromium } = require('playwright');
const assert = (c, m) => { if (!c) { throw new Error('FAILED: ' + m); } console.log('ok', m); };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/index.html');
  await page.waitForTimeout(800);
  const hero = () => page.textContent('#heroName');
  assert(await hero() === 'RaiPlay', 'initial focus on first tile (apps.json loaded)');
  assert(await page.locator('.tile-wrap').count() === 5, '5 tiles rendered from apps.json');
  await page.screenshot({ path: process.argv[2] + '/launcher_home.png' });
  await page.keyboard.press('ArrowRight');
  assert(await hero() === 'YouTube', 'RIGHT moves focus');
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight');
  assert(await hero() === 'Jellyfin', 'RIGHT clamps at end of row');
  await page.keyboard.press('ArrowDown');
  assert(await hero() === 'Info sistema', 'DOWN moves to next row, column clamped');
  await page.waitForTimeout(600);
  await page.screenshot({ path: process.argv[2] + '/launcher_row2.png' });
  await page.keyboard.press('Enter');
  assert(await page.isVisible('#diag'), 'OK on Info sistema opens diagnostics');
  const diag = await page.textContent('#diagOut');
  assert(diag.includes('Viewport:     1920 x 1080'), 'diagnostics reports viewport');
  await page.waitForTimeout(600);
  await page.screenshot({ path: process.argv[2] + '/launcher_diag.png' });
  await page.keyboard.press('Backspace');
  assert(!(await page.isVisible('#diag')), 'Back (keyCode 8) closes diagnostics');
  await page.reload(); await page.waitForTimeout(600);
  assert(await hero() === 'Info sistema', 'focus restored after reload (localStorage)');
  await page.route('https://www.raiplay.it/**', r => r.fulfill({ status: 200, contentType: 'text/html', body: 'stub' }));
  await page.keyboard.press('ArrowUp');
  assert(await hero() === 'RaiPlay', 'UP returns to app row');
  const nav = page.waitForRequest(r => r.url().startsWith('https://www.raiplay.it/') && r.isNavigationRequest());
  await page.keyboard.press('Enter');
  await nav;
  console.log('ok OK on app tile navigates to its URL');
  // 720p surface keeps the same proportions
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForTimeout(600);
  await page.screenshot({ path: process.argv[2] + '/launcher_720p.png' });
  assert(errors.length === 0, 'no page errors: ' + errors.join('; '));
  await browser.close();
  console.log('ALL LAUNCHER TESTS PASSED');
})().catch(e => { console.error(e.message); process.exit(1); });
